#!/usr/bin/env python3
"""Regenerate the README progress block and docs/progress-map.svg from the tree.

Tiers per retail function (config/us/funcs.csv):
  T4  tagged in a filed source (src/, outside src/control/) and EXACT under tools/score.py
  T3  certified behaviour exact by the A5/A7 oracle (not built yet: none)
  T2  tagged in a source but not T4: still differing, or EXACT but not yet filed into its
      translation unit (the compiler control set in src/control/)
  T1  not started
Fenced: library code (config/us/tus.csv class lib:*), not counted. Unknown: unidentified code
in the library region, not counted until classified.
M1 = T3 + T4, M2 = T4, both over the game class only.

Usage: python3 tools/progress.py            (runs the grader on every source; ~10 s per file)
"""
import bisect
import csv
import datetime
import glob
import html
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SVG = os.path.join(ROOT, 'docs/progress-map.svg')
README = os.path.join(ROOT, 'README.md')
COLORS = {'T4': '#2f9e55', 'T3': '#3a7bd5', 'T2': '#e2a52b', 'T1': '#cfd3d8', 'fenced': '#9a72c8', 'unknown': '#8f949b'}


def grade():
    """{addr: (status, path)} for every @implements in src/."""
    out = {}
    files = sorted(glob.glob(os.path.join(ROOT, 'src/**/*.c'), recursive=True) +
                   glob.glob(os.path.join(ROOT, 'src/**/*.cpp'), recursive=True))
    for path in files:
        p = subprocess.run([sys.executable, '-I', os.path.join(ROOT, 'tools/score.py'), path],
                           capture_output=True, text=True)
        for line in p.stdout.splitlines():
            m = re.match(r'(\w+)\s+0x([0-9a-f]+)\s', line)
            if m:
                out[int(m.group(2), 16)] = (m.group(1), os.path.relpath(path, ROOT))
    return out


def tiers():
    funcs = [(int(r['addr'], 16), int(r['size'])) for r in csv.DictReader(open(os.path.join(ROOT, 'config/us/funcs.csv')))]
    tus = list(csv.DictReader(open(os.path.join(ROOT, 'config/us/tus.csv'))))
    starts = [int(t['start'], 16) for t in tus]
    graded = grade()
    rows = []
    for a, z in funcs:
        t = tus[bisect.bisect_right(starts, a) - 1]
        cls = t['class']
        if cls.startswith('lib:'):
            tier = 'fenced'
        elif cls == 'unknown':
            tier = 'unknown'
        else:
            st, path = graded.get(a, (None, None))
            if st is None:
                tier = 'T1'
            elif st == 'EXACT' and not path.startswith('src/control/'):
                tier = 'T4'
            else:
                tier = 'T2'
        path = graded.get(a, (None, ''))[1] or ''
        rows.append(dict(addr=a, size=z, tu=int(t['tu']), cls=cls, tier=tier, ctrl=path.startswith('src/control/')))
    return rows, tus


def bar(frac, width=40):
    full = int(round(frac * width))
    return '█' * full + '░' * (width - full)


def block(rows):
    game = [r for r in rows if r['tier'] in ('T1', 'T2', 'T3', 'T4')]
    gb, gn = sum(r['size'] for r in game), len(game)
    m1 = [r for r in game if r['tier'] in ('T3', 'T4')]
    m2 = [r for r in game if r['tier'] == 'T4']
    t2 = [r for r in game if r['tier'] == 'T2']
    fen = [r for r in rows if r['tier'] == 'fenced']
    unk = [r for r in rows if r['tier'] == 'unknown']
    day = datetime.date.today().isoformat()
    f = lambda xs: sum(r['size'] for r in xs)  # noqa: E731
    lines = [
        '<!-- PROGRESS:BEGIN: generated by tools/progress.py; do not edit by hand -->',
        f'_Snapshot {day}._',
        '',
        '```',
        'M1  Behaviour exact (T3 + T4)',
        f'    {bar(f(m1) / gb)}  {100 * f(m1) / gb:5.1f}%   {f(m1):,} / {gb:,} B   {len(m1):,} / {gn:,} fns',
        'M2  Byte exact (T4)',
        f'    {bar(f(m2) / gb)}  {100 * f(m2) / gb:5.1f}%   {f(m2):,} / {gb:,} B   {len(m2):,} / {gn:,} fns',
        '```',
        '',
        '| Code | Functions | Bytes | Counted |',
        '|---|---:|---:|---|',
        f'| **Game** (the denominator) | {gn:,} | {gb:,} | yes: T4 {len(m2)}, T3 {len(m1) - len(m2)}, T2 {len(t2)}, T1 {gn - len(m1) - len(t2):,} |',
        f'| Libraries: libstdc++, newlib, libgcc (fenced) | {len(fen):,} | {f(fen):,} | no; matched from their own source or linked |',
        f'| Unidentified, in the library region | {len(unk):,} | {f(unk):,} | not until classified |',
        '',
        f'T2 includes the {sum(1 for r in t2 if r["ctrl"])} functions of the compiler control set (`src/control/`), '
        'most of them byte-exact; they become T4 once filed into their translation units.',
        '<!-- PROGRESS:END -->',
    ]
    return '\n'.join(lines)


def squarify(items, x, y, w, h):
    """Squarified treemap: items = [(weight, payload)] sorted descending -> [(x, y, w, h, payload)]."""
    out = []
    items = [it for it in items if it[0] > 0]
    total = sum(v for v, _ in items)
    if not items or w <= 0 or h <= 0:
        return out
    scale = w * h / total
    rects = [(v * scale, p) for v, p in items]
    while rects:
        short = min(w, h)
        row, rest = [rects[0]], rects[1:]

        def worst(r):
            s = sum(a for a, _ in r)
            return max(max(short * short * a / (s * s), s * s / (short * short * a)) for a, _ in r)
        while rest and worst(row + [rest[0]]) <= worst(row):
            row.append(rest.pop(0))
        s = sum(a for a, _ in row)
        if w >= h:
            cw = s / h
            cy = y
            for a, p in row:
                ch = a / cw
                out.append((x, cy, cw, ch, p))
                cy += ch
            x, w = x + cw, w - cw
        else:
            ch = s / w
            cx = x
            for a, p in row:
                cwid = a / ch
                out.append((cx, y, cwid, ch, p))
                cx += cwid
            y, h = y + ch, h - ch
        rects = rest
    return out


def svg(rows, tus):
    W, H, LEG = 1200, 640, 36
    by_tu = {}
    for r in rows:
        by_tu.setdefault(r['tu'], []).append(r)
    groups = sorted(((sum(r['size'] for r in fs), (k, fs)) for k, fs in by_tu.items()), key=lambda g: -g[0])
    parts = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H + LEG}" width="{W}" height="{H + LEG}" '
             'font-family="Helvetica, Arial, sans-serif" font-size="12">',
             f'<rect width="{W}" height="{H + LEG}" fill="#ffffff"/>']
    for gx, gy, gw, gh, (k, fs) in squarify(groups, 0, 0, W, H):
        t = tus[k]
        parts.append(f'<g><title>object {k} ({html.escape(t["class"])}) {t["start"]}-{t["end"]}, {len(fs)} fns</title>')
        inner = sorted(((r['size'], r) for r in fs), key=lambda i: -i[0])
        for x, y, w, h, r in squarify(inner, gx, gy, gw, gh):
            parts.append(f'<rect x="{x:.2f}" y="{y:.2f}" width="{w:.2f}" height="{h:.2f}" fill="{COLORS[r["tier"]]}">'
                         f'<title>f_{r["addr"]:06x} {r["size"]} B {r["tier"]}</title></rect>')
        parts.append(f'<rect x="{gx:.2f}" y="{gy:.2f}" width="{gw:.2f}" height="{gh:.2f}" fill="none" stroke="#ffffff" stroke-width="1.2"/></g>')
    lx = 8
    for label, key in (('T4 byte-exact', 'T4'), ('T3 behaviour exact', 'T3'), ('T2 in the tree', 'T2'),
                       ('T1 not started', 'T1'), ('library (fenced)', 'fenced'), ('unidentified', 'unknown')):
        parts.append(f'<rect x="{lx}" y="{H + 12}" width="14" height="14" fill="{COLORS[key]}"/>'
                     f'<text x="{lx + 20}" y="{H + 24}" fill="#333333">{label}</text>')
        lx += 20 + 7 * len(label) + 18
    parts.append('</svg>')
    os.makedirs(os.path.dirname(SVG), exist_ok=True)
    open(SVG, 'w').write('\n'.join(parts) + '\n')


def main():
    rows, tus = tiers()
    s = open(README).read()
    new = block(rows)
    s = re.sub(r'<!-- PROGRESS:BEGIN.*?<!-- PROGRESS:END -->', lambda _: new, s, flags=re.S)
    open(README, 'w').write(s)
    svg(rows, tus)
    print(new)
    print(f'wrote {os.path.relpath(SVG, ROOT)}')


if __name__ == '__main__':
    main()
