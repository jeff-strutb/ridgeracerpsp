#!/usr/bin/env python3
"""Write docs/UNTAGGED.md: the C++ methods that @implements code refers to but no tag claims,
and the calls to library symbols that tools/analysis/libsyms.py refuses.

    tools/untagged.py            write docs/UNTAGGED.md
    tools/untagged.py --check    rebuild it and compare with the committed file

A callee is a C++ method symbol (mangled _ZN...) that tools/score.py cannot place: no tag
claims it, and a method name is not taken as an address.  Its sites are found by grading
every @implements of every real file with score.py in collection mode: a function whose
references all pass except references to such callees is PENDING, and each of those
references gives the retail address the callee must have (retail's target minus the addend).

  Group 1: a real source file defines the callee's body, but no tag claims it.  The body
           is graded by score.py as if tagged at the address the sites agree on.
  Group 2: no real source file defines a body for the callee.

"callers" counts the @implements functions in real files whose code refers to the callee;
references from data only (vtable slots) are listed apart.  Nothing under src/ is changed.
"""
import sys
from collections import Counter, defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import score                    # noqa: E402

OUT = score.ROOT / 'docs' / 'UNTAGGED.md'


def collect():
    tree = score.Tree()
    g = score.Grader(tree)
    files = [p for p in score.source_files() if score.is_real(p)]
    tree.compile_many(files)
    units = [tree.unit(p) for p in files]
    names, defs = set(), defaultdict(list)
    for u in units:
        if u.obj is None:
            continue
        for s in u.obj.functions():
            if s.bind != score.STB_LOCAL:
                defs[s.name].append((u, s))
        for rl in u.obj.rels.values():
            for r in rl:
                sy = r.sym
                if sy.type == score.STT_SECTION or sy.bind == score.STB_LOCAL:
                    continue
                if sy.name.startswith('_ZN') and g.resolve(u, sy, 0).kind == 'none':
                    names.add(sy.name)
    g.collect = names
    sites = defaultdict(list)
    incode = defaultdict(set)
    for u in units:
        for t in u.tags:
            if t.kind != 'implements' or t.region != 'us':
                continue
            s, _ = u.claim[t]
            if s is not None:
                for r in u.obj.rels.get(s.shndx, []):
                    if s.value <= r.off < s.value + s.size and r.sym.name in names:
                        incode[r.sym.name].add(t.addr)
            r = g.grade(u, t)
            if r['verdict'] == 'PENDING':
                for n, a, _ in r['pending']:
                    sites[n].append((a, t.addr))
    g2 = score.Grader(tree)
    rows = []
    for n in sorted(names):
        c = Counter(a for a, _ in sites[n])
        addr, k = c.most_common(1)[0] if c else (None, 0)
        row = dict(symbol=n, sites=len(sites[n]), disagreeing=len(sites[n]) - k, address=addr,
                   callers=len(incode[n]), defined='', verdict='', detail='')
        if n in defs:
            u, s = defs[n][0]
            row['defined'] = u.rel
            if addr is not None:
                tag = score.Tag('implements', addr, 'us', n, u.rel, 0, True)
                u.claim[tag] = (s, 'exact')
                r = g2.grade(u, tag)
                g2.finalize([r])
                row['verdict'], row['detail'] = r['verdict'], r['detail']
        rows.append(row)
    return rows, refused_calls(units)


def refused_calls(units):
    """(symbol, call address, function, file) for every call in @implements code to a symbol
    that libsyms.csv lists as refused."""
    import csv
    with open(score.ROOT / 'config' / 'us' / 'libsyms.csv') as fh:
        refused = {r['symbol']: r for r in csv.DictReader(fh) if r['accepted'] != 'yes'}
    out = []
    for u in units:
        if u.obj is None:
            continue
        for t in u.tags:
            if t.kind != 'implements':
                continue
            s, _ = u.claim[t]
            if s is None:
                continue
            for r in u.obj.rels.get(s.shndx, []):
                if s.value <= r.off < s.value + s.size and r.sym.name in refused:
                    out.append((r.sym.name, t.addr + r.off - s.value, t.addr, u.rel, t.line,
                                refused[r.sym.name]['reason'].split(' | ')[0]))
    return sorted(out)


def render(rows, calls):
    def a(x):
        return '%#08x' % x if x is not None else 'none observed'
    g1 = [r for r in rows if r['defined']]
    g2 = [r for r in rows if not r['defined']]
    md = ['# Untagged methods and refused library calls', '',
          'Generated by `tools/untagged.py`; do not edit by hand. Nothing under `src/` was changed.',
          '', 'A callee is a C++ method that `@implements` code refers to but no tag claims. '
          '"sites" are its references in otherwise-EXACT `@implements` functions (score.py '
          'collection mode); "disagreeing" are sites that point elsewhere; "callers" are '
          '`@implements` functions whose code refers to it (0 means only data, such as a '
          'vtable, refers to it).', '']
    for title, grp, body in (('1. Body present in a real file, no tag', g1, True),
                             ('2. No body in the tree', g2, False)):
        md += ['## %s: %d (%d with code callers, %d with an agreed address)' % (
            title, len(grp), sum(r['callers'] > 0 for r in grp),
            sum(r['address'] is not None for r in grp)), '']
        hdr = '| symbol | callers | sites | disagreeing | agreed address |'
        sep = '|---|---:|---:|---:|---|'
        if body:
            hdr += ' defined in | score.py at that address |'
            sep += '---|---|'
        md += [hdr, sep]
        for r in grp:
            line = '| `%s` | %d | %d | %d | %s |' % (r['symbol'], r['callers'], r['sites'],
                                                    r['disagreeing'], a(r['address']))
            if body:
                line += ' %s | %s |' % (r['defined'], ('%s: %s' % (r['verdict'], r['detail'])
                                                      if r['verdict'] else 'not graded: no '
                                                      'agreed address').replace('|', '/'))
            md.append(line)
        md.append('')
    md += ['## 3. Calls to library symbols that libsyms.py refuses', '',
           '| symbol | call at | in function | file | tag line | why refused |',
           '|---|---|---|---|---:|---|']
    for n, at, f, rel, line, why in calls:
        md.append('| `%s` | %#08x | %#08x | %s | %d | %s |' % (n, at, f, rel, line,
                                                               why.replace('|', '/')))
    return '\n'.join(md) + '\n'


def main(argv):
    rows, calls = collect()
    text = render(rows, calls)
    if argv[1:] == ['--check']:
        same = OUT.is_file() and OUT.read_text() == text
        print('untagged --check:', 'same' if same else 'DIFFERS from the committed file')
        return 0 if same else 1
    OUT.write_text(text)
    g1 = sum(1 for r in rows if r['defined'])
    print('wrote %s: %d callees (%d with a body, %d without), %d refused library calls' % (
        OUT.relative_to(score.ROOT), len(rows), g1, len(rows) - g1, len(calls)))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
